  function runB2(alive) {
    const clamp = (v) => Math.max(0, Math.min(1, v));
    const code = ov.groups.pgcode || [];
    let next = 0, typed = 0;
    ov.hlForm.pa.classList.add("on"); ov.hlForm.pg.classList.add("on");
    return new Promise((done) => {
      let t0 = null;
      const frame = () => {
        let now;
        if (!alive()) return done();
        now = performance.now();
        if (t0 === null) t0 = now;
        const x = B2_X0 + (now - t0) / 1000 * B2_SPEED;
        while (next < B2_ENTER.length && B2_ENTER[next][0] <= x) showGroup(B2_ENTER[next++][1]);
        for (const [key, [a, b]] of Object.entries(B2_FILL)) if (ov.fills[key]) ov.fills[key].style.transform = `scaleX(${clamp((x - a) / (b - a))})`;
        const want = Math.ceil(code.length * clamp((x - B2_CODE[0]) / (B2_CODE[1] - B2_CODE[0])));
        while (typed < want) {
          const el = code[typed++];
          el.classList.add("type"); el.classList.remove("off");
          const e = ov.ends.get(el);
          if (e) { ov.caret2.setAttribute("x", e[0] + .6); ov.caret2.setAttribute("y", e[1] - 10); ov.caret2.setAttribute("opacity", 1); }
        }
        if (typed === code.length) ov.caret2.setAttribute("opacity", 0);
        if (x < B2_X1) return setTimeout(frame, 16);
        ov.hlForm.pa.classList.remove("on"); ov.hlForm.pg.classList.remove("on");
        done();
      };
      frame();
    });
  }
