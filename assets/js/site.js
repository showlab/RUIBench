  // (the controls unmute it); it pauses when scrolled away, and a viewer's own pause holds until they play it again
  function demoReel() {
    const v = $("#video video");
    if (!v || REDUCED) return;
    v.muted = true;
    let ours = false, held = false;
    v.addEventListener("pause", () => { if (!ours) held = true; ours = false; });
    v.addEventListener("play", () => { held = false; });
    new IntersectionObserver((es) => es.forEach((e) => {
      if (e.isIntersecting) { if (v.paused && !held) { const p = v.play(); if (p) p.catch(() => {}); } }
      else if (!v.paused) { ours = true; v.pause(); }
    }), { threshold: 0.35 }).observe(v);
  }
