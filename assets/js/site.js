  async function rkAct(form, frame, alive) {      // one reply: down to the interface, the call to the engine, frames back
    const { box, dots } = rk;
    rkOn(box[form]); rkOn(box.skill);
    if (!(await rkMove(dots.ink, RK_PATH.reply, 380, alive))) return false;
    setTimeout(() => rkPulse("wr"), 330);
    if (!(await rkMove(dots.ink, RK_PATH.call, 1050, alive))) return false;
    rkOn(box.engine);
    if (!(await rkMove(dots.ink, RK_PATH.log, 300, alive))) return false;
    rkShow(frame);
    setTimeout(() => rkPulse("cam"), 380);
    if (!(await rkMove(dots.blue, RK_PATH.frames, 1050, alive))) return false;
    rkOn(box.engine, false); rkOn(box[form], false);
    return true;
  }
  async function rkEpisode(alive) {
    const { box, dots } = rk, a = rk.agent;
    rk.agent = (a + 1) % 3;                        // each round another harness and model; the interface is what varies
    rkOn(box.harness[a]); rkOn(box.model[a]);
    rkShow("f0");
    if (!(await rkMove(dots.ink, RK_PATH.instr, 380, alive))) return;
    await sleep(150);
    if (!(await rkType("r1", alive))) return;
    if (!(await rkAct("pa", "f1", alive))) return;
    if (!(await rkType("r2", alive))) return;
    if (!(await rkAct("pg", "f2", alive))) return;
    rkOn(box.skill, false);
    for (const g of ["up1", "c0", "c1", "c2", "amh", "up2"]) { if (!alive()) return; rkShow(g); await sleep(230); }
    rkOn(box.verdict);
    await sleep(350);
    if (!(await rkMove(dots.red, RK_PATH.back, 800, alive))) return;
    rkPulse("x");                                  // withheld: the verdict never reaches the agent
    await sleep(2600);
  }
